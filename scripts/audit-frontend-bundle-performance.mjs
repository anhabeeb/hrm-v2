import fs from "node:fs";
import path from "node:path";
import { gzipSync } from "node:zlib";

const root = process.cwd();
const distRoot = path.join(root, "frontend", "dist");
const assetsRoot = path.join(distRoot, "assets");
const reportPath = path.join(root, "docs", "performance", "frontend-bundle-phase10.md");

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function read(file) {
  return fs.readFileSync(file, "utf8");
}

function exists(file) {
  return fs.existsSync(file);
}

function formatKb(bytes) {
  return `${(bytes / 1024).toFixed(1)} kB`;
}

function assetInfo(file) {
  const absolute = path.join(assetsRoot, file);
  const source = fs.readFileSync(absolute);
  return {
    file,
    bytes: source.length,
    gzipBytes: gzipSync(source).length
  };
}

function parseIndexReferences(indexHtml) {
  const refs = [];
  const assetPattern = /(?:src|href)="\/?([^"]+\.(?:js|css))"/g;
  let match;
  while ((match = assetPattern.exec(indexHtml))) refs.push(match[1].replace(/^\/+/, ""));
  return refs;
}

function parseBuildLogWarnings() {
  const candidates = [".codex-phase10-build.log", ".codex-build.log"].map((file) => path.join(root, file));
  const warnings = [];
  for (const file of candidates) {
    if (!exists(file)) continue;
    const log = read(file);
    if (/Circular chunk/i.test(log)) warnings.push("Circular chunk warning detected in build log.");
    if (/Some chunks are larger/i.test(log)) warnings.push("Vite chunk-size warning detected in build log.");
  }
  return warnings;
}

assert(exists(distRoot), "frontend/dist is missing. Run npm run build before auditing the frontend bundle.");
assert(exists(assetsRoot), "frontend/dist/assets is missing. Run npm run build before auditing the frontend bundle.");

const indexPath = path.join(distRoot, "index.html");
assert(exists(indexPath), "frontend/dist/index.html is missing.");

const indexHtml = read(indexPath);
const indexRefs = parseIndexReferences(indexHtml);
const mainScript = indexRefs.find((ref) => /^assets\/index-.*\.js$/.test(ref));
assert(mainScript, "Could not find the built main application entry in index.html.");

const jsAssets = fs.readdirSync(assetsRoot).filter((file) => file.endsWith(".js")).map(assetInfo);
const cssAssets = fs.readdirSync(assetsRoot).filter((file) => file.endsWith(".css")).map(assetInfo);
const initialAssets = indexRefs
  .filter((ref) => ref.startsWith("assets/"))
  .map((ref) => ref.replace("assets/", ""))
  .filter((file) => exists(path.join(assetsRoot, file)))
  .map(assetInfo);

const mainInfo = assetInfo(mainScript.replace("assets/", ""));
const initialJsBytes = initialAssets.filter((asset) => asset.file.endsWith(".js")).reduce((sum, asset) => sum + asset.bytes, 0);
const initialCssBytes = initialAssets.filter((asset) => asset.file.endsWith(".css")).reduce((sum, asset) => sum + asset.bytes, 0);
const totalJsBytes = jsAssets.reduce((sum, asset) => sum + asset.bytes, 0);
const totalCssBytes = cssAssets.reduce((sum, asset) => sum + asset.bytes, 0);
const largestChunks = [...jsAssets].sort((a, b) => b.bytes - a.bytes).slice(0, 12);
const routeChunkMarkers = [
  "EmployeeProfilePage",
  "LifecyclePage",
  "PayrollRunDetailPage",
  "PayrollAdminPages",
  "DataTransferPage",
  "AttendanceRecordsPage",
  "RosterWeeklyPage",
  "ReportsPage",
  "AdminHelpGuidePage"
];
const routeChunks = routeChunkMarkers.map((marker) => ({
  marker,
  matched: jsAssets.find((asset) => asset.file.startsWith(marker))
}));
const buildWarnings = parseBuildLogWarnings();

const previousMainEntryBytes = 211630;
const mainEntryChangeBytes = mainInfo.bytes - previousMainEntryBytes;

const report = `# Frontend Bundle Performance Phase 10

Generated by \`npm run audit:frontend-bundle-performance\`.

## Summary

| Metric | Value |
| --- | ---: |
| Main application entry | ${formatKb(mainInfo.bytes)} (${formatKb(mainInfo.gzipBytes)} gzip) |
| Previous accepted main entry baseline | ${formatKb(previousMainEntryBytes)} |
| Main entry change | ${mainEntryChangeBytes <= 0 ? "-" : "+"}${formatKb(Math.abs(mainEntryChangeBytes))} |
| Initial JavaScript referenced by index.html | ${formatKb(initialJsBytes)} |
| Initial CSS referenced by index.html | ${formatKb(initialCssBytes)} |
| Total JavaScript across lazy chunks | ${formatKb(totalJsBytes)} |
| Total CSS | ${formatKb(totalCssBytes)} |
| JavaScript chunk count | ${jsAssets.length} |
| CSS chunk count | ${cssAssets.length} |

## Initial Assets

| Asset | Size | Gzip |
| --- | ---: | ---: |
${initialAssets.map((asset) => `| \`${asset.file}\` | ${formatKb(asset.bytes)} | ${formatKb(asset.gzipBytes)} |`).join("\n")}

## Largest JavaScript Chunks

| Chunk | Size | Gzip |
| --- | ---: | ---: |
${largestChunks.map((asset) => `| \`${asset.file}\` | ${formatKb(asset.bytes)} | ${formatKb(asset.gzipBytes)} |`).join("\n")}

## Route Split Checks

| Route or heavy page marker | Lazy chunk |
| --- | --- |
${routeChunks.map((entry) => `| ${entry.marker} | ${entry.matched ? `\`${entry.matched.file}\`` : "Missing"} |`).join("\n")}

## Phase 10 Optimizations

- The authenticated startup path uses slim API modules for auth, search, notifications, session settings, and app events.
- The broad HRM API surface is emitted as a lazy \`api-*.js\` chunk and is no longer required by the main app entry.
- Heavy route modules remain behind route-level lazy imports.
- Sidebar route prefetch runs only after idle time or user intent, and respects module visibility plus data-saver/slow-connection hints.
- Background job drawer code is lazy-loaded only when the drawer opens.
- Cloudflare Pages headers keep \`index.html\` fresh while allowing immutable caching for hashed assets.

## Build Warnings

${buildWarnings.length ? buildWarnings.map((warning) => `- ${warning}`).join("\n") : "- No circular chunk or Vite chunk-size warnings were detected in available build logs."}

## Deferred

- Further splitting of the very large Employee 360 page can be done by tab-level chunks if future profiling shows it is still a hot path.
- Additional prefetch priorities can be tuned with production telemetry once the new route prefetch registry has real usage data.
`;

fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, report, "utf8");

console.log(`Frontend bundle audit complete. Main entry: ${formatKb(mainInfo.bytes)}; initial JS: ${formatKb(initialJsBytes)}.`);
console.log(`Report written to ${path.relative(root, reportPath).replaceAll("\\", "/")}.`);
