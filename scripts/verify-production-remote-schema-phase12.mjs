import fs from "node:fs";
import path from "node:path";
import {
  extractRowsFromWrangler,
  parseSchema,
  quoteIdent,
  readText,
  rootDir,
  runWranglerSql,
  seedPath
} from "./remote-d1-schema-utils.mjs";
import { writeReport } from "./phase12-utils.mjs";

const requiredTables = [
  "document_upload_sessions",
  "background_jobs",
  "background_job_events",
  "app_events",
  "report_export_artifacts",
  "attendance_summary_snapshots",
  "payroll_summary_snapshots",
  "dashboard_summary_snapshots",
  "performance_api_metrics",
  "performance_frontend_metrics",
  "performance_job_metrics",
  "performance_build_metrics"
];

const repairPath = path.join(rootDir, "database", "remote_schema_repair_phase12_generated.sql");

function remoteRows(sql) {
  return extractRowsFromWrangler(runWranglerSql(sql));
}

function seedBlockers(remoteTables) {
  const blockers = [];
  const seed = readText(seedPath);
  for (const match of seed.matchAll(/INSERT\s+OR\s+(?:IGNORE|REPLACE)\s+INTO\s+([A-Za-z_][\w]*)\s*\(([^)]+)\)/gi)) {
    const table = match[1];
    const remote = remoteTables[table];
    if (!remote) continue;
    const columns = match[2].split(",").map((part) => part.trim().replaceAll('"', ""));
    for (const column of columns) {
      if (!remote.columns[column]) blockers.push({ table, column, reason: "Referenced by database/seed.sql." });
    }
  }
  return blockers;
}

function markdown(report) {
  const list = (items, empty = "_None._") => {
    if (!items.length) return empty;
    return items.map((item) => `- ${typeof item === "string" ? item : JSON.stringify(item)}`).join("\n");
  };
  return `# Phase 12 Remote D1 Schema Readiness

Generated: ${report.generated_at}

Final readiness status: **${report.status}**

${report.blocked_reason ? `Blocked reason: ${report.blocked_reason}\n` : ""}

## Required Tables

${list(report.required_tables)}

## Missing Tables

${list(report.missing_tables)}

## Missing Columns

${list(report.missing_columns.map((item) => `${item.table}.${item.column}`))}

## Missing Indexes

${list(report.missing_indexes.map((item) => `${item.table}.${item.index}`))}

## Seed Blockers

${list(report.seed_blockers.map((item) => `${item.table}.${item.column} - ${item.reason}`))}

## Unsafe Differences

${list(report.unsafe_differences)}

## Additive Repair SQL

${report.repair_sql_path ? `Generated: \`${report.repair_sql_path}\`` : "_No additive repair SQL was needed._"}

## Safety

This verifier is read-only. It does not apply remote repair SQL, drop tables, drop columns, delete data, or rewrite production rows.
`;
}

async function main() {
  const schema = parseSchema();
  const report = {
    generated_at: new Date().toISOString(),
    status: "BLOCKED",
    required_tables: requiredTables,
    missing_tables: [],
    missing_columns: [],
    missing_indexes: [],
    seed_blockers: [],
    unsafe_differences: [],
    repair_sql_path: null,
    blocked_reason: ""
  };

  try {
    const tableRows = remoteRows("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT GLOB '_cf_*' ORDER BY name;");
    if (tableRows.length === 0) throw new Error("sqlite_master returned zero tables for the remote D1 database.");
    const indexRows = remoteRows("SELECT name, tbl_name, sql FROM sqlite_master WHERE type = 'index' AND name NOT LIKE 'sqlite_%' AND tbl_name NOT GLOB '_cf_*' ORDER BY name;");
    const remoteTables = {};
    for (const row of tableRows) {
      const tableName = String(row.name);
      const columnRows = remoteRows(`PRAGMA table_info(${JSON.stringify(tableName)});`);
      remoteTables[tableName] = {
        sql: String(row.sql ?? ""),
        columns: Object.fromEntries(columnRows.map((column) => [String(column.name), column])),
        indexes: indexRows.filter((index) => String(index.tbl_name) === tableName)
      };
    }

    const repairStatements = [
      "-- Phase 12 additive remote schema repair generated by verify-production-remote-schema-phase12.mjs.",
      "-- Review before applying. No DROP/DELETE/UPDATE statements are generated here."
    ];

    for (const tableName of requiredTables) {
      const local = schema.tables[tableName];
      const remote = remoteTables[tableName];
      if (!local) {
        report.unsafe_differences.push(`Required table ${tableName} is missing from local database/schema.sql.`);
        continue;
      }
      if (!remote) {
        report.missing_tables.push(tableName);
        repairStatements.push(local.createSql);
        continue;
      }
      for (const column of local.columnOrder) {
        if (!remote.columns[column]) {
          report.missing_columns.push({ table: tableName, column, definition: local.columns[column] });
          repairStatements.push(`ALTER TABLE ${quoteIdent(tableName)} ADD COLUMN ${local.columns[column]};`);
        }
      }
      const remoteIndexNames = new Set(remote.indexes.map((index) => String(index.name)));
      for (const indexDef of schema.indexes[tableName] ?? []) {
        if (!remoteIndexNames.has(indexDef.name)) {
          report.missing_indexes.push({ table: tableName, index: indexDef.name, definition: indexDef.sql });
          repairStatements.push(indexDef.sql);
        }
      }
    }

    report.seed_blockers = seedBlockers(remoteTables).filter((item) => requiredTables.includes(item.table) || item.table === "permissions");

    const needsRepair = report.missing_tables.length || report.missing_columns.length || report.missing_indexes.length;
    if (needsRepair) {
      fs.writeFileSync(repairPath, `${repairStatements.join("\n\n")}\n`);
      report.repair_sql_path = "database/remote_schema_repair_phase12_generated.sql";
      report.status = report.seed_blockers.length || report.unsafe_differences.length ? "BLOCKED" : "PASS WITH REPAIR AVAILABLE";
    } else {
      if (fs.existsSync(repairPath)) fs.unlinkSync(repairPath);
      report.status = report.seed_blockers.length || report.unsafe_differences.length ? "BLOCKED" : "PASS";
    }
  } catch (error) {
    report.status = "BLOCKED";
    report.blocked_reason = error instanceof Error ? error.message : String(error);
    if (process.env.HRM_PHASE12_REQUIRE_REMOTE_SCHEMA === "true") {
      writeReport("docs/production/phase12-remote-d1-schema-readiness.md", markdown(report));
      throw error;
    }
  }

  writeReport("docs/production/phase12-remote-d1-schema-readiness.md", markdown(report));
  console.log(`Phase 12 remote D1 schema readiness: ${report.status}`);
  console.log("Report written to docs/production/phase12-remote-d1-schema-readiness.md.");
  if (report.status === "BLOCKED" && process.env.HRM_PHASE12_REQUIRE_REMOTE_SCHEMA === "true") process.exit(1);
}

main().catch((error) => {
  console.error("Phase 12 remote D1 schema readiness failed.");
  console.error(error.message);
  process.exit(1);
});
