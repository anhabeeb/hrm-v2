import fs from "node:fs";
import path from "node:path";
import { gzipSync } from "node:zlib";

const root = process.cwd();
const distRoot = path.join(root, "frontend", "dist");
const assetsRoot = path.join(distRoot, "assets");
const reportPath = path.join(root, "docs", "performance", "performance-regression-budget-phase11.md");

const budgets = {
  mainEntryKb: 275,
  initialJsKb: 520,
  largestChunkKb: 850,
  payloadWarningBytes: 500 * 1024,
  apiWarningMs: 750,
  apiCriticalMs: 2000
};

const failures = [];
const warnings = [];

function read(file) {
  return fs.readFileSync(path.join(root, file), "utf8");
}

function exists(file) {
  return fs.existsSync(path.join(root, file));
}

function formatKb(bytes) {
  return (bytes / 1024).toFixed(1);
}

function assetInfo(file) {
  const source = fs.readFileSync(path.join(assetsRoot, file));
  return {
    file,
    bytes: source.length,
    gzipBytes: gzipSync(source).length
  };
}

function parseIndexReferences(indexHtml) {
  const refs = [];
  const assetPattern = /(?:src|href)="\/?([^"]+\.(?:js|css))"/g;
  let match;
  while ((match = assetPattern.exec(indexHtml))) refs.push(match[1].replace(/^\/+/, ""));
  return refs;
}

function check(condition, message) {
  if (!condition) failures.push(message);
}

if (!fs.existsSync(distRoot) || !fs.existsSync(assetsRoot)) {
  failures.push("frontend/dist is missing. Run npm run build before audit:performance-regression-budget.");
} else {
  const indexPath = path.join(distRoot, "index.html");
  check(fs.existsSync(indexPath), "frontend/dist/index.html is missing.");
  if (fs.existsSync(indexPath)) {
    const refs = parseIndexReferences(fs.readFileSync(indexPath, "utf8"));
    const initialAssets = refs
      .filter((ref) => ref.startsWith("assets/"))
      .map((ref) => ref.replace("assets/", ""))
      .filter((file) => fs.existsSync(path.join(assetsRoot, file)))
      .map(assetInfo);
    const jsAssets = fs.readdirSync(assetsRoot).filter((file) => file.endsWith(".js")).map(assetInfo);
    const mainEntry = initialAssets.find((asset) => /^index-.*\.js$/.test(asset.file));
    const initialJsBytes = initialAssets.filter((asset) => asset.file.endsWith(".js")).reduce((sum, asset) => sum + asset.bytes, 0);
    const initialCssBytes = initialAssets.filter((asset) => asset.file.endsWith(".css")).reduce((sum, asset) => sum + asset.bytes, 0);
    const largestChunk = [...jsAssets].sort((a, b) => b.bytes - a.bytes)[0] ?? { file: "none", bytes: 0, gzipBytes: 0 };

    check(Boolean(mainEntry), "Main index JS entry was not found in built index.html.");
    if (mainEntry && mainEntry.bytes / 1024 > budgets.mainEntryKb) failures.push(`Main entry ${formatKb(mainEntry.bytes)} KB exceeds ${budgets.mainEntryKb} KB budget.`);
    if (initialJsBytes / 1024 > budgets.initialJsKb) failures.push(`Initial JS ${formatKb(initialJsBytes)} KB exceeds ${budgets.initialJsKb} KB budget.`);
    if (largestChunk.bytes / 1024 > budgets.largestChunkKb) failures.push(`Largest chunk ${largestChunk.file} is ${formatKb(largestChunk.bytes)} KB and exceeds ${budgets.largestChunkKb} KB budget.`);

    const report = `# Performance Regression Budget Phase 11

Generated by \`npm run audit:performance-regression-budget\`.

## frontend bundle budgets

| Budget | Limit | Current |
| --- | ---: | ---: |
| Main entry | ${budgets.mainEntryKb} KB | ${mainEntry ? `${formatKb(mainEntry.bytes)} KB` : "missing"} |
| Initial JavaScript | ${budgets.initialJsKb} KB | ${formatKb(initialJsBytes)} KB |
| Largest lazy chunk | ${budgets.largestChunkKb} KB | ${largestChunk.file} (${formatKb(largestChunk.bytes)} KB) |
| Initial CSS | Informational | ${formatKb(initialCssBytes)} KB |

## endpoint and payload budgets

| Budget | Limit |
| --- | ---: |
| API warning threshold | ${budgets.apiWarningMs} ms |
| API critical threshold | ${budgets.apiCriticalMs} ms |
| Payload warning threshold | ${formatKb(budgets.payloadWarningBytes)} KB |

## Status

${failures.length ? failures.map((failure) => `- FAIL: ${failure}`).join("\n") : "- PASS: source/build budgets are within accepted limits."}
${warnings.length ? warnings.map((warning) => `- WARN: ${warning}`).join("\n") : ""}
`;
    fs.mkdirSync(path.dirname(reportPath), { recursive: true });
    fs.writeFileSync(reportPath, report, "utf8");
  }
}

const workerPerformance = read("worker/src/utils/performance.ts");
const workerPerformanceMetrics = read("worker/src/utils/performance-metrics.ts");
const performanceRoutes = read("worker/src/routes/performance.ts");
const appRoutes = read("frontend/src/routes/AppRoutes.tsx");
const dashboard = read("frontend/src/pages/PerformanceDashboardPage.tsx");
const d1Audit = read("scripts/audit-d1-query-performance.mjs");

check(workerPerformance.includes("PAYLOAD_WARNING_THRESHOLD_BYTES"), "payload warning helpers are missing from Worker performance middleware.");
check(workerPerformance.includes("API_WARNING_THRESHOLD_MS") && workerPerformance.includes("API_CRITICAL_THRESHOLD_MS"), "API timing thresholds are missing.");
check(workerPerformanceMetrics.includes("SENSITIVE_METADATA_KEY"), "sensitive logging guard is missing from metrics writer.");
check(performanceRoutes.includes("performance.metrics.view") && performanceRoutes.includes("parsePaginationParams"), "performance dashboard route must be admin-protected and paginated.");
check(appRoutes.includes("settings/performance"), "performance dashboard route is missing from AppRoutes.");
check(dashboard.includes("PermissionDeniedState"), "performance dashboard UI must deny unauthorized access.");
check(d1Audit.includes("Potential unbounded ordered lists") && d1Audit.includes("SELECT * occurrences"), "D1 audit findings must remain part of performance regression guard.");

if (/\b(window\.)?(alert|confirm|prompt)\s*\(/.test(dashboard)) failures.push("Performance dashboard introduced browser alert/confirm/prompt.");
if (/request_body|response_body|password_hash|raw_token|document_contents|bank_account_number|net_salary|gross_salary/i.test(workerPerformanceMetrics)) failures.push("Metrics writer appears to reference sensitive payload values.");

if (failures.length) {
  console.error("Performance regression budget audit failed:");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}

console.log("Performance regression budget audit passed.");
console.log(`Report written to ${path.relative(root, reportPath).replaceAll("\\", "/")}.`);
